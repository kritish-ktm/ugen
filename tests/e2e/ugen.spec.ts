test('the production PWA reloads and navigates offline', async ({ page, context }) => {
  await page.goto('/')
  const manifest = await page.request.get('/manifest.webmanifest')
  expect((await manifest.json()).display).toBe('standalone')
  for (const file of ['icon-192.png', 'icon-512.png', 'icon-maskable.png']) expect((await page.request.get('/' + file)).ok()).toBe(true)
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Kalender', exact: true })).toBeVisible()
  await expect(page.getByText('Du er offline', { exact: true })).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'Mere' }).click()
  await expect(page.getByRole('heading', { name: 'Mere', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Åbn ugeplan' }).click()
  await expect(page.getByRole('button', { name: /Tilføj påmindelse / })).toHaveCount(7)
})

test('axe detects no WCAG A/AA violations on primary routes or day sheet', async ({ page }) => {
  for (const path of ['/', '/valuta', '/nyheder', '/rejse', '/mere', '/mere/om']) {
    await page.goto(path)
    await expect(page.locator('h1')).toBeVisible()
    const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect.soft(result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map(node => node.target) })), path).toEqual([])
  }
  await page.goto('/')
  await page.getByRole('button', { name: 'Tilføj påmindelse' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([])
})

