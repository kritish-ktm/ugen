import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('mobile navigation and the dated week summary', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/playground')
  await expect(page).toHaveURL(/\/valuta$/)
  await page.getByRole('navigation').getByRole('link', { name: 'Kalender' }).click()
  await expect(page.getByRole('heading', { name: 'Kalender', exact: true })).toBeVisible()
  const week = page.getByRole('list', { name: 'Ugens dage' })
  await expect(week.getByRole('listitem')).toHaveCount(7)
  await expect(week.locator('[aria-current="date"] time')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('calendar jumps to ISO week 53 and persists a dated reminder', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Gå til uge' }).click()
  const jump = page.getByRole('dialog')
  await jump.getByLabel('År', { exact: true }).selectOption('2026')
  await jump.getByLabel('Ugenummer').selectOption('53')
  await jump.getByRole('button', { name: 'Vis uge', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Uge', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: /fredag 1. januar 2027/i }).click()
  const day = page.getByRole('dialog')
  await expect(day.getByText('53 · 2026')).toBeVisible()
  await expect(day.locator('p').filter({ hasText: /^Nytårsdag$/ })).toBeVisible()
  await day.getByRole('button', { name: 'Ny påmindelse' }).click()
  await day.getByLabel('Titel').fill('Årets første plan')
  await day.getByLabel('Tidspunkt').fill('10:00')
  await day.getByLabel('Noter').fill('Husk kaffe')
  await day.getByRole('button', { name: 'Gem påmindelse' }).click()
  await expect(day.getByText('Årets første plan')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(day).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Mere' }).click()
  await expect(page.getByText('Årets første plan')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Årets første plan')).toBeVisible()
  await page.getByRole('button', { name: 'Slet Årets første plan' }).click()
  await expect(page.getByText('Årets første plan')).toHaveCount(0)
})

