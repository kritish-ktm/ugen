  await expect(page.getByLabel('Omregnet beløb')).toHaveText('67,00')
  await page.getByRole('button', { name: 'Byt valutaer' }).click()
  await expect(page.getByLabel('Omregnet beløb')).toHaveText('500,00')
  await expect(page.getByRole('img', { name: 'Kurshistorik for EUR / DKK' })).toBeVisible()
  rate = .135
  await page.getByRole('button', { name: 'Opdater kurser' }).click()
  await expect(page.getByLabel('Omregnet beløb')).toHaveText('496,30')
  await page.getByRole('button', { name: 'Vælg valuta' }).click()
